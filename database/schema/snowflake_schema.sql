-- Snowflake schema for vehicle marketplace source records.
-- Prices retain source-specific numeric values; no currency conversion is applied.
CREATE SCHEMA IF NOT EXISTS snowflake;

CREATE TABLE snowflake.dim_source_dataset (
    source_dataset_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    container_csv_name TEXT NOT NULL,
    source_name_value TEXT NULL,
    CONSTRAINT uq_snowflake_source_dataset
        UNIQUE (container_csv_name, source_name_value)
);

CREATE TABLE snowflake.dim_brand (
    brand_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_dataset_key BIGINT NOT NULL
        REFERENCES snowflake.dim_source_dataset (source_dataset_key),
    brand_name_raw TEXT NOT NULL,
    CONSTRAINT uq_snowflake_brand_source_name
        UNIQUE (source_dataset_key, brand_name_raw),
    CONSTRAINT uq_snowflake_brand_key_source
        UNIQUE (brand_key, source_dataset_key)
);

CREATE TABLE snowflake.dim_model (
    model_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_dataset_key BIGINT NOT NULL
        REFERENCES snowflake.dim_source_dataset (source_dataset_key),
    brand_key BIGINT NULL,
    source_model_field TEXT NOT NULL,
    model_name_raw TEXT NOT NULL,
    full_model_name_raw TEXT NULL,
    CONSTRAINT fk_snowflake_model_brand_source
        FOREIGN KEY (brand_key, source_dataset_key)
        REFERENCES snowflake.dim_brand (brand_key, source_dataset_key),
    CONSTRAINT uq_snowflake_model_key_source
        UNIQUE (model_key, source_dataset_key)
);

CREATE TABLE snowflake.dim_location (
    location_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_dataset_name TEXT NOT NULL,
    city_name_raw TEXT NOT NULL,
    CONSTRAINT uq_snowflake_location_source_city
        UNIQUE (source_dataset_name, city_name_raw)
);

CREATE TABLE snowflake.dim_vehicle_year (
    vehicle_year_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_year SMALLINT NOT NULL UNIQUE
);

CREATE TABLE snowflake.dim_fuel (
    fuel_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_dataset_name TEXT NOT NULL,
    fuel_type_raw TEXT NOT NULL,
    CONSTRAINT uq_snowflake_fuel_source_type
        UNIQUE (source_dataset_name, fuel_type_raw)
);

CREATE TABLE snowflake.dim_transmission (
    transmission_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_dataset_name TEXT NOT NULL,
    transmission_type_raw TEXT NOT NULL,
    CONSTRAINT uq_snowflake_transmission_source_type
        UNIQUE (source_dataset_name, transmission_type_raw)
);

CREATE TABLE snowflake.dim_seller_type (
    seller_type_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_dataset_name TEXT NOT NULL,
    seller_type_raw TEXT NOT NULL,
    CONSTRAINT uq_snowflake_seller_source_type
        UNIQUE (source_dataset_name, seller_type_raw)
);

CREATE TABLE snowflake.fact_vehicle_marketplace (
    vehicle_marketplace_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_dataset_key BIGINT NOT NULL
        REFERENCES snowflake.dim_source_dataset (source_dataset_key),
    model_key BIGINT NULL
        REFERENCES snowflake.dim_model (model_key),
    location_key BIGINT NULL
        REFERENCES snowflake.dim_location (location_key),
    vehicle_year_key BIGINT NULL
        REFERENCES snowflake.dim_vehicle_year (vehicle_year_key),
    fuel_key BIGINT NULL REFERENCES snowflake.dim_fuel (fuel_key),
    transmission_key BIGINT NULL
        REFERENCES snowflake.dim_transmission (transmission_key),
    seller_type_key BIGINT NULL
        REFERENCES snowflake.dim_seller_type (seller_type_key),

    source_file_name TEXT NOT NULL,
    source_record_ordinal BIGINT NOT NULL CHECK (source_record_ordinal > 0),
    source_row_identifier_field TEXT NULL,
    source_row_identifier_raw TEXT NULL,

    combined_cars_selling_price_raw NUMERIC NULL,
    combined_cars_present_price_raw NUMERIC NULL,
    combined_cars2_price_raw NUMERIC NULL,
    combined_cars3_selling_price_raw NUMERIC NULL,
    odometer_km NUMERIC NULL,
    combined_cars2_car_age_raw NUMERIC NULL,
    combined_cars3_vehicle_age_raw NUMERIC NULL,
    combined_cars_owner_raw NUMERIC NULL,
    combined_cars3_mileage_raw NUMERIC NULL,
    combined_cars3_engine_raw NUMERIC NULL,
    combined_cars3_max_power_raw NUMERIC NULL,
    combined_cars3_seats_raw NUMERIC NULL,

    CONSTRAINT fk_snowflake_fact_model_source
        FOREIGN KEY (model_key, source_dataset_key)
        REFERENCES snowflake.dim_model (model_key, source_dataset_key),
    CONSTRAINT uq_snowflake_fact_source_record
        UNIQUE (source_file_name, source_record_ordinal)
);

CREATE INDEX ix_snowflake_brand_source_dataset
    ON snowflake.dim_brand (source_dataset_key);
CREATE INDEX ix_snowflake_model_source_dataset
    ON snowflake.dim_model (source_dataset_key);
CREATE INDEX ix_snowflake_model_brand
    ON snowflake.dim_model (brand_key);
CREATE INDEX ix_snowflake_fact_source_dataset
    ON snowflake.fact_vehicle_marketplace (source_dataset_key);
CREATE INDEX ix_snowflake_fact_model ON snowflake.fact_vehicle_marketplace (model_key);
CREATE INDEX ix_snowflake_fact_location
    ON snowflake.fact_vehicle_marketplace (location_key);
CREATE INDEX ix_snowflake_fact_vehicle_year
    ON snowflake.fact_vehicle_marketplace (vehicle_year_key);
CREATE INDEX ix_snowflake_fact_fuel ON snowflake.fact_vehicle_marketplace (fuel_key);
CREATE INDEX ix_snowflake_fact_transmission
    ON snowflake.fact_vehicle_marketplace (transmission_key);
CREATE INDEX ix_snowflake_fact_seller_type
    ON snowflake.fact_vehicle_marketplace (seller_type_key);
