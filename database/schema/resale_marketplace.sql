CREATE SCHEMA IF NOT EXISTS marketplace;

CREATE TABLE IF NOT EXISTS marketplace.customer_role (
    customer_account_id INTEGER NOT NULL
        REFERENCES customer_portal.customer_account(id) ON DELETE CASCADE,
    role_name VARCHAR(16) NOT NULL
        CHECK (role_name IN ('BUYER', 'SELLER')),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (customer_account_id, role_name)
);

CREATE TABLE IF NOT EXISTS marketplace.moderator_account (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS marketplace.vehicle_listing (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_account_id INTEGER NOT NULL
        REFERENCES customer_portal.customer_account(id) ON DELETE CASCADE,
    brand VARCHAR(100) NOT NULL,
    model VARCHAR(120) NOT NULL,
    manufacturing_year SMALLINT NOT NULL
        CHECK (manufacturing_year BETWEEN 1886 AND 2100),
    fuel_type VARCHAR(40) NOT NULL,
    transmission VARCHAR(40) NOT NULL,
    kilometres_driven BIGINT NOT NULL CHECK (kilometres_driven >= 0),
    asking_price NUMERIC(14, 2) NOT NULL CHECK (asking_price >= 0),
    price_currency CHAR(3) NOT NULL,
    description TEXT NOT NULL,
    location VARCHAR(160) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING_APPROVAL'
        CHECK (status IN (
            'PENDING_APPROVAL',
            'APPROVED_ACTIVE',
            'REJECTED',
            'WITHDRAWN',
            'SIMULATED_PURCHASE'
        )),
    seller_verification_status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CONSTRAINT vehicle_listing_seller_verification_check
        CHECK (seller_verification_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    seller_verified_by INTEGER
        REFERENCES marketplace.moderator_account(id) ON DELETE SET NULL,
    seller_verified_at TIMESTAMPTZ,
    seller_verification_note VARCHAR(1000),
    moderation_note VARCHAR(1000),
    reviewed_by INTEGER
        REFERENCES marketplace.moderator_account(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

