CREATE INDEX IF NOT EXISTS idx_vehicle_listing_public
    ON marketplace.vehicle_listing(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vehicle_listing_seller
    ON marketplace.vehicle_listing(seller_account_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vehicle_listing_filters
    ON marketplace.vehicle_listing(
        status, brand, manufacturing_year, fuel_type, transmission, price_currency
    );

CREATE TABLE IF NOT EXISTS marketplace.vehicle_listing_photo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id INTEGER NOT NULL
        REFERENCES marketplace.vehicle_listing(id) ON DELETE CASCADE,
    display_order SMALLINT NOT NULL CHECK (display_order >= 0),
    content_type VARCHAR(32) NOT NULL
        CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    image_data BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (listing_id, display_order)
);

CREATE TABLE IF NOT EXISTS marketplace.vehicle_ownership_document (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id INTEGER NOT NULL
        REFERENCES marketplace.vehicle_listing(id) ON DELETE CASCADE,
    display_order SMALLINT NOT NULL CHECK (display_order >= 0),
    content_type VARCHAR(32) NOT NULL CHECK (
        content_type IN ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')
    ),
    document_data BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (listing_id, display_order)
);

CREATE TABLE IF NOT EXISTS marketplace.simulated_transaction (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL UNIQUE,
    listing_id INTEGER NOT NULL UNIQUE
        REFERENCES marketplace.vehicle_listing(id) ON DELETE RESTRICT,
    buyer_account_id INTEGER NOT NULL
        REFERENCES customer_portal.customer_account(id) ON DELETE RESTRICT,
    seller_account_id INTEGER NOT NULL
        REFERENCES customer_portal.customer_account(id) ON DELETE RESTRICT,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount >= 0),
    price_currency CHAR(3) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'SIMULATED_SUCCESS'
        CHECK (status = 'SIMULATED_SUCCESS'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_simulated_transaction_created
    ON marketplace.simulated_transaction(created_at DESC);
