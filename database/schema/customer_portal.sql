CREATE SCHEMA IF NOT EXISTS customer_portal;

CREATE TABLE IF NOT EXISTS customer_portal.customer_account (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    phone_number VARCHAR(32) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    profile_image_mime VARCHAR(32) NOT NULL,
    profile_image_data BYTEA NOT NULL,
    account_status VARCHAR(16) NOT NULL DEFAULT 'free',
    premium_plan VARCHAR(16),
    premium_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT customer_account_subscription_check CHECK (
        (account_status = 'free' AND premium_plan IS NULL
            AND premium_expires_at IS NULL)
        OR
        (account_status = 'premium' AND premium_plan IN ('monthly', 'yearly')
            AND premium_expires_at IS NOT NULL)
    )
);
