-- Additive Migration for Online Vehicle Marketplace Upgrade
-- Preserves all existing tables, records, constraints, and warehouse structures.

-- 1. Extend customer_portal.customer_account with buyer and seller membership columns
ALTER TABLE customer_portal.customer_account
    ADD COLUMN IF NOT EXISTS buyer_tier VARCHAR(16) NOT NULL DEFAULT 'FREE',
    ADD COLUMN IF NOT EXISTS buyer_tier_expires_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS seller_membership_status VARCHAR(16) NOT NULL DEFAULT 'INACTIVE',
    ADD COLUMN IF NOT EXISTS seller_membership_expires_at TIMESTAMPTZ;

-- 2. Extend marketplace.vehicle_listing with moderation and status flags
ALTER TABLE marketplace.vehicle_listing
    ADD COLUMN IF NOT EXISTS is_flagged BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS flag_reason TEXT,
    ADD COLUMN IF NOT EXISTS suspension_reason TEXT,
    ADD COLUMN IF NOT EXISTS suspended_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS suspended_by INTEGER REFERENCES marketplace.moderator_account(id) ON DELETE SET NULL;

ALTER TABLE marketplace.vehicle_listing
    DROP CONSTRAINT IF EXISTS vehicle_listing_status_check;

ALTER TABLE marketplace.vehicle_listing
    ADD CONSTRAINT vehicle_listing_status_check
        CHECK (status IN (
            'PENDING_APPROVAL',
            'APPROVED_ACTIVE',
            'REJECTED',
            'WITHDRAWN',
            'SIMULATED_PURCHASE',
            'SUSPENDED',
            'FLAGGED',
            'SOFT_REMOVED'
        ));

-- 3. Moderation Audit Log Table
CREATE TABLE IF NOT EXISTS marketplace.moderation_audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id INTEGER NOT NULL REFERENCES marketplace.vehicle_listing(id) ON DELETE CASCADE,
    moderator_id INTEGER REFERENCES marketplace.moderator_account(id) ON DELETE SET NULL,
    action VARCHAR(32) NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_moderation_audit_log_listing 
    ON marketplace.moderation_audit_log(listing_id, created_at DESC);

-- 4. Vehicle Bookings (50% deposit, remaining 50% balance, demo payment status)
CREATE TABLE IF NOT EXISTS marketplace.vehicle_booking (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR(64) NOT NULL UNIQUE,
    listing_id INTEGER NOT NULL REFERENCES marketplace.vehicle_listing(id) ON DELETE RESTRICT,
    buyer_account_id INTEGER NOT NULL REFERENCES customer_portal.customer_account(id) ON DELETE RESTRICT,
    seller_account_id INTEGER NOT NULL REFERENCES customer_portal.customer_account(id) ON DELETE RESTRICT,
    total_price NUMERIC(14, 2) NOT NULL CHECK (total_price >= 0),
    deposit_amount NUMERIC(14, 2) NOT NULL CHECK (deposit_amount >= 0),
    remaining_balance NUMERIC(14, 2) NOT NULL CHECK (remaining_balance >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    payment_status VARCHAR(32) NOT NULL DEFAULT 'CONFIRMED_DEMO'
        CHECK (payment_status IN ('PENDING_PAYMENT', 'CONFIRMED_DEMO', 'CANCELLED', 'COMPLETED')),
    booking_status VARCHAR(32) NOT NULL DEFAULT 'CONFIRMED'
        CHECK (booking_status IN ('CONFIRMED', 'CANCELLED', 'COMPLETED')),
    demo_payment_reference VARCHAR(64) NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_vehicle_booking_buyer 
    ON marketplace.vehicle_booking(buyer_account_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vehicle_booking_seller 
    ON marketplace.vehicle_booking(seller_account_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vehicle_booking_listing 
    ON marketplace.vehicle_booking(listing_id);

-- 5. Membership Transactions (Separate from bookings)
CREATE TABLE IF NOT EXISTS marketplace.membership_transaction (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference VARCHAR(64) NOT NULL UNIQUE,
    customer_account_id INTEGER NOT NULL REFERENCES customer_portal.customer_account(id) ON DELETE CASCADE,
    membership_type VARCHAR(32) NOT NULL CHECK (membership_type IN ('BUYER_BASIC', 'BUYER_PREMIUM', 'SELLER_YEARLY')),
    amount NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    status VARCHAR(32) NOT NULL DEFAULT 'CONFIRMED_DEMO' CHECK (status IN ('PENDING', 'CONFIRMED_DEMO', 'FAILED')),
    payment_method VARCHAR(32) NOT NULL DEFAULT 'UPI_QR_DEMO',
    demo_upi_reference VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_membership_transaction_account 
    ON marketplace.membership_transaction(customer_account_id, created_at DESC);

-- 6. Buyer Favourites
CREATE TABLE IF NOT EXISTS marketplace.buyer_favourite (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_account_id INTEGER NOT NULL REFERENCES customer_portal.customer_account(id) ON DELETE CASCADE,
    listing_id INTEGER NOT NULL REFERENCES marketplace.vehicle_listing(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (customer_account_id, listing_id)
);

CREATE INDEX IF NOT EXISTS idx_buyer_favourite_account 
    ON marketplace.buyer_favourite(customer_account_id, created_at DESC);
